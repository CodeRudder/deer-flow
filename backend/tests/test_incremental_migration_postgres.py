@pytest.fixture(scope="module")
def disposable_postgres_dsn() -> str:
    raw_dsn = os.getenv("DEER_FLOW_TEST_POSTGRES_DSN")
    if not raw_dsn:
        pytest.skip("set DEER_FLOW_TEST_POSTGRES_DSN to run PostgreSQL migration integration tests")

    import psycopg
    from psycopg import sql
    from psycopg.conninfo import make_conninfo

    try:
        bootstrap = psycopg.connect(raw_dsn, autocommit=True)
    except psycopg.Error:
        pytest.skip("DEER_FLOW_TEST_POSTGRES_DSN is not reachable")
    database_name = f"deerflow_migration_it_{uuid.uuid4().hex[:16]}"
    with bootstrap:
        with bootstrap.cursor() as cursor:
            cursor.execute("SELECT role_row.rolcreatedb OR role_row.rolsuper FROM pg_catalog.pg_roles role_row WHERE role_row.rolname = current_user")
            if not bool(cursor.fetchone()[0]):
                pytest.skip("DEER_FLOW_TEST_POSTGRES_DSN role cannot create an isolated test database")
            cursor.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(database_name)))
        test_dsn = make_conninfo(raw_dsn, dbname=database_name)
        try:
            yield test_dsn
        finally:
            with bootstrap.cursor() as cursor:
                cursor.execute(
                    "SELECT pg_catalog.pg_terminate_backend(pid) FROM pg_catalog.pg_stat_activity WHERE datname = %s AND pid <> pg_catalog.pg_backend_pid()",
                    (database_name,),
                )
                cursor.execute(sql.SQL("DROP DATABASE {}").format(sql.Identifier(database_name)))


