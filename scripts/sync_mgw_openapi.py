#!/usr/bin/env python3
"""Sync the Media Gateway (MGW) OpenAPI snapshot used by the media-gateway-api skill.

The skill's quick-reference (SKILL.md) can drift from the live gateway contract.
This script keeps a machine-checkable snapshot in the repo:

  - skills/public/media-gateway-api/openapi.json          (committed snapshot)
  - skills/public/media-gateway-api/endpoints-summary.md  (generated one-line-per-endpoint digest)

Usage:
  python scripts/sync_mgw_openapi.py            # fetch live /openapi.json, write snapshot + summary
  python scripts/sync_mgw_openapi.py --diff     # compare live vs snapshot, print changed endpoints
  python scripts/sync_mgw_openapi.py --diff --offline   # compare snapshot vs summary (no network)

Exit codes:
  sync mode: 0 on success, 1 on failure
  --diff:    0 = no change, 1 = contract changed, 2 = failure

The gateway base URL is read from .env (MEDIA_GATEWAY_BASE_URL). Multiple candidate
addresses may be given (comma-separated); the first one that answers wins. The env
var / CLI flag override the .env value.
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
SKILL_DIR = REPO_ROOT / "skills" / "public" / "media-gateway-api"
SNAPSHOT_PATH = SKILL_DIR / "openapi.json"
SUMMARY_PATH = SKILL_DIR / "endpoints-summary.md"
ENV_PATH = REPO_ROOT / ".env"

# Fallback candidates tried in order when resolving the gateway base URL.
DEFAULT_CANDIDATES = [
    "http://172.17.0.1:8000",
    "http://127.0.0.1:8000",
]

HTTP_TIMEOUT_S = 10


def load_env(path: Path = ENV_PATH) -> dict[str, str]:
    """Parse a simple KEY=VALUE .env file (ignores comments/blank lines)."""
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, val = line.partition("=")
        values[key.strip()] = val.strip().strip('"').strip("'")
    return values


def resolve_base_urls(
    override: str | None = None,
    env: dict[str, str] | None = None,
) -> list[str]:
    """Return candidate gateway base URLs, first live one wins."""
    env = env if env is not None else load_env()
    raw = override or env.get("MEDIA_GATEWAY_BASE_URL", "")
    candidates = [u.strip().rstrip("/") for u in raw.split(",") if u.strip()]
    if not candidates:
        candidates = DEFAULT_CANDIDATES
    return candidates


def fetch_openapi(base_url: str) -> dict[str, Any]:
    url = f"{base_url.rstrip('/')}/openapi.json"
    with urllib.request.urlopen(url, timeout=HTTP_TIMEOUT_S) as resp:
        if resp.status != 200:
            raise RuntimeError(f"{url} -> HTTP {resp.status}")
        return json.loads(resp.read().decode("utf-8"))


def fetch_live(candidates: list[str]) -> tuple[str, dict[str, Any]]:
    errors: list[str] = []
    for base in candidates:
        try:
            return base, fetch_openapi(base)
        except Exception as exc:  # noqa: BLE001 - report all candidates
            errors.append(f"{base}: {exc}")
    raise RuntimeError("no candidate gateway answered:\n  " + "\n  ".join(errors))


def summarize(spec: dict[str, Any]) -> str:
    """Render a one-line-per-endpoint markdown digest, grouped by path."""
    lines = [
        "<!-- GENERATED by scripts/sync_mgw_openapi.py — do not edit by hand. -->",
        "",
        f"# MGW endpoints summary ({spec.get('info', {}).get('title', '')} v{spec.get('info', {}).get('version', '?')})",
        "",
    ]
    for path in sorted(spec.get("paths", {})):
        lines.append(f"### `{path}`")
        for method in ("get", "post", "put", "patch", "delete", "head", "options"):
            op = spec["paths"][path].get(method)
            if not op:
                continue
            summary = (op.get("summary") or op.get("operationId") or "").replace("\n", " ").strip()
            lines.append(f"- `{method.upper()} {path}` — {summary}")
        lines.append("")
    return "\n".join(lines)


def endpoint_index(spec: dict[str, Any]) -> dict[str, str]:
    """Map 'METHOD /path' -> summary for a spec."""
    index: dict[str, str] = {}
    for path, methods in spec.get("paths", {}).items():
        for method, op in methods.items():
            if method.lower() not in {"get", "post", "put", "patch", "delete", "head", "options"}:
                continue
            index[f"{method.upper()} {path}"] = (op.get("summary") or "").replace("\n", " ").strip()
    return index


def diff_specs(old: dict[str, Any], new: dict[str, Any]) -> list[str]:
    """Return a human-readable list of endpoint-level changes (empty = same)."""
    old_idx = endpoint_index(old)
    new_idx = endpoint_index(new)
    changes: list[str] = []
    for key in sorted(set(old_idx) - set(new_idx)):
        changes.append(f"REMOVED  {key}")
    for key in sorted(set(new_idx) - set(old_idx)):
        changes.append(f"ADDED    {key}  ({new_idx[key]})")
    for key in sorted(set(old_idx) & set(new_idx)):
        if old_idx[key] != new_idx[key]:
            changes.append(f"CHANGED  {key}  summary: {old_idx[key]!r} -> {new_idx[key]!r}")
    return changes


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--diff", action="store_true", help="compare live spec vs snapshot, print changes, exit 1 if changed")
    parser.add_argument("--base-url", help="override gateway base URL(s), comma-separated candidates")
    parser.add_argument("--offline", action="store_true", help="with --diff: check snapshot vs summary consistency only (no network)")
    args = parser.parse_args(argv)

    try:
        if args.offline:
            if not SNAPSHOT_PATH.exists() or not SUMMARY_PATH.exists():
                print("FAIL: snapshot or summary missing", file=sys.stderr)
                return 2
            snapshot = json.loads(SNAPSHOT_PATH.read_text(encoding="utf-8"))
            expected = summarize(snapshot)
            actual = SUMMARY_PATH.read_text(encoding="utf-8")
            if expected != actual:
                print("CHANGED: summary out of sync with snapshot — rerun scripts/sync_mgw_openapi.py")
                return 1
            print("OK: snapshot and summary consistent")
            return 0

        candidates = resolve_base_urls(args.base_url)
        base, live = fetch_live(candidates)

        if args.diff:
            if not SNAPSHOT_PATH.exists():
                print(f"NO SNAPSHOT at {SNAPSHOT_PATH} — run sync mode first")
                return 1
            snapshot = json.loads(SNAPSHOT_PATH.read_text(encoding="utf-8"))
            changes = diff_specs(snapshot, live)
            if changes:
                print(f"MGW contract changed vs snapshot ({len(changes)} endpoint change(s)):")
                for c in changes:
                    print(f"  {c}")
                print("→ run: python scripts/sync_mgw_openapi.py  (then commit snapshot + summary)")
                return 1
            print(f"OK: live gateway ({base}) matches snapshot ({len(endpoint_index(live))} endpoints)")
            return 0

        # sync mode
        SKILL_DIR.mkdir(parents=True, exist_ok=True)
        SNAPSHOT_PATH.write_text(json.dumps(live, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        SUMMARY_PATH.write_text(summarize(live), encoding="utf-8")
        print(f"OK: synced snapshot from {base} — {len(endpoint_index(live))} endpoints")
        for p in (SNAPSHOT_PATH, SUMMARY_PATH):
            try:
                shown = p.relative_to(REPO_ROOT)
            except ValueError:
                shown = p
            print(f"    {shown}")
        return 0
    except Exception as exc:  # noqa: BLE001
        print(f"FAIL: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
